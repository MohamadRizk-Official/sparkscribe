// Builds privacy.html and terms.html from the Markdown drafts in docs/launch/ (the single source of their text).
// The pages carry a "Draft" banner and highlight [CONFIRM] / [LEGAL REVIEW] notes until the text is final.
//   node scripts/build-legal.mjs            (run again whenever the drafts change)
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// inline: escape, then **bold**, `code`, [text](url), and review markers
function inline(s) {
  let h = esc(s);
  h = h.replace(/\*\*\[(LEGAL REVIEW|CONFIRM)([^\]]*)\]\*\*/g, (_, k, rest) => `<mark class="legal-flag${k === 'CONFIRM' ? ' confirm' : ''}">${k === 'CONFIRM' ? 'To confirm' : 'Legal review'}${esc(rest.replace(/^[:\s]+/, ': ')).replace(/^: $/, '')}</mark>`);
  h = h.replace(/\[(LEGAL REVIEW|CONFIRM)([^\]]*)\]/g, (_, k, rest) => `<mark class="legal-flag${k === 'CONFIRM' ? ' confirm' : ''}">${k === 'CONFIRM' ? 'To confirm' : 'Legal review'}${rest.replace(/^[:\s]+/, ': ').replace(/^: $/, '')}</mark>`);
  h = h.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  h = h.replace(/`([^`]+)`/g, '<code>$1</code>');
  h = h.replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+|\/[^)\s]*)\)/g, '<a href="$2">$1</a>');
  return h;
}

function toHtml(md) {
  const lines = md.replace(/\r/g, '').split('\n');
  const out = [];
  let i = 0;
  const para = [];
  const flush = () => { if (para.length) { out.push(`<p>${inline(para.join(' '))}</p>`); para.length = 0; } };
  while (i < lines.length) {
    const l = lines[i];
    if (/^\s*$/.test(l)) { flush(); i++; continue; }
    let m;
    if ((m = /^(#{1,3}) (.*)$/.exec(l))) {
      flush();
      const level = m[1].length + 0;
      const id = m[2].toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      out.push(level === 1 ? `<h1>${inline(m[2])}</h1>` : `<h${level} id="${id}">${inline(m[2])}</h${level}>`);
      i++; continue;
    }
    if (/^> /.test(l)) { flush(); const q = []; while (i < lines.length && /^> ?/.test(lines[i])) q.push(lines[i++].replace(/^> ?/, '')); out.push(`<aside class="legal-note">${inline(q.join(' '))}</aside>`); continue; }
    if (/^\|/.test(l)) {
      flush();
      const rows = [];
      while (i < lines.length && /^\|/.test(lines[i])) rows.push(lines[i++]);
      const cells = (r) => r.replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
      const [head, , ...body] = rows;
      out.push(`<div class="legal-table"><table><thead><tr>${cells(head).map((c) => `<th>${inline(c)}</th>`).join('')}</tr></thead><tbody>${body.map((r) => `<tr>${cells(r).map((c) => `<td>${inline(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`);
      continue;
    }
    if (/^\s*- /.test(l)) {
      flush();
      const items = [];
      while (i < lines.length && (/^\s*- /.test(lines[i]) || (/^\s{2,}\S/.test(lines[i]) && items.length))) {
        if (/^\s*- /.test(lines[i])) items.push(lines[i].replace(/^\s*- /, '')); else items[items.length - 1] += ' ' + lines[i].trim();
        i++;
      }
      out.push(`<ul>${items.map((t) => `<li>${inline(t)}</li>`).join('')}</ul>`);
      continue;
    }
    if (/^\*\*[^*]+:\*\*/.test(l.trim())) flush(); // "**Label:** …" lines start their own paragraph
    para.push(l.trim());
    i++;
  }
  flush();
  return out.join('\n');
}

const page = (title, description, body) => `<!doctype html>
<!-- GENERATED by scripts/build-legal.mjs from docs/launch/*.md: edit the Markdown, then re-run. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="theme-color" content="#04050d" />
    <meta name="robots" content="noindex" />
    <title>${title}${FINAL ? '' : ' (draft)'} — SparkScribe</title>
    <meta name="description" content="${description}" />
    <link rel="icon" href="/favicon.svg" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Space+Grotesk:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500&display=swap" rel="stylesheet" />
    <link rel="stylesheet" href="/src/style.css" />
  </head>
  <body>
    <div class="bg-grid" aria-hidden="true"></div>
    <header class="topbar">
      <!-- sparkscribe:brand -->
      <div class="topbar-right"><div id="accountSlot"></div></div>
    </header>
    <main class="app legal-page">
      ${FINAL ? '' : `<div class="legal-banner" role="note"><strong>Draft, not yet in effect.</strong> This document is being prepared for SparkScribe's launch and is under review. Highlighted notes mark details still to be confirmed or reviewed.</div>`}
      <article class="panel legal-doc">
${body}
      </article>
      <!-- sparkscribe:legal -->
    </main>
    <script type="module" src="/src/pages/legal.js"></script>
  </body>
</html>
`;

// --final: the reviewed, published version. Refuses while any [CONFIRM] / [LEGAL REVIEW] note or placeholder remains,
// and drops the draft banner. Without it, pages are built as drafts (and production builds refuse them).
const FINAL = process.argv.includes('--final');
const src = (f) => readFileSync(resolve(ROOT, 'docs/launch', f), 'utf8').replace(/\r/g, '')
  .replace(/^> \*\*Draft for review[\s\S]*?\n\n/m, ''); // the reviewer note at the top becomes the page banner
if (FINAL) {
  const open = [];
  for (const f of ['04-privacy-policy-DRAFT.md', '05-terms-of-service-DRAFT.md']) {
    const t = src(f);
    const notes = (t.match(/\[(CONFIRM|LEGAL REVIEW)[^\]]*\]/g) || []).length;
    // any other [bracketed choice or blank] (not a Markdown link) is still a decision to make: [30], [REFUND POLICY]…
    const blanks = (t.replace(/\[(CONFIRM|LEGAL REVIEW)[^\]]*\]/g, '').match(/\[[^\]\n]+\](?!\()/g) || []).length;
    if (/—\s*DRAFT/.test(t)) open.push(`${f}: the title still says DRAFT`);
    if (notes || blanks) open.push(`${f}: ${notes} review note(s), ${blanks} placeholder(s)`);
  }
  if (open.length) { console.error(`Not final yet:\n  ${open.join('\n  ')}`); process.exit(1); }
}
writeFileSync(resolve(ROOT, 'privacy.html'), page('Privacy Policy', 'How SparkScribe handles your data.', toHtml(src('04-privacy-policy-DRAFT.md'))));
writeFileSync(resolve(ROOT, 'terms.html'), page('Terms of Service', 'The terms for using SparkScribe.', toHtml(src('05-terms-of-service-DRAFT.md'))));
console.log('wrote privacy.html, terms.html');
